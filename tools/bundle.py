from pathlib import Path
root = Path(__file__).resolve().parents[1]
names = ['Schema', 'Loader', 'Planner', 'Builder', 'GameAdapter', 'UI']
parts = ['-- BABFT Auto Builder: generated by tools/bundle.py; edit src/*.luau instead.\n']
for name in names:
    text = (root / 'src' / (name + '.luau')).read_text(encoding='utf-8')
    parts.append(f'\n-- BEGIN {name}\nlocal {name} = (function()\n{text}\nend)()\n-- END {name}\n')
parts.append('\nUI.start(Schema, Loader, Planner, Builder, GameAdapter)\n')
(root / 'BABFT_AutoBuilder.lua').write_text(''.join(parts),encoding='utf-8',newline='\n')
